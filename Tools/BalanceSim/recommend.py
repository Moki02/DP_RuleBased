def current_value(cfg, knob, sweep):
    paths, kind = sweep["knobs"][knob]["paths"], sweep["knobs"][knob]["kind"]
    if kind == "scale":
        return 1.0
    node = cfg
    for k in paths[0].split("."):
        node = node[int(k)] if isinstance(node, list) else node[k]
    return node


def main():
    with open(os.path.join(ROOT, "results", "sweep.json"), encoding="utf8") as f:
        sw = json.load(f)
    cfg = config.balance()
    best = sw["best"]
    sens = sw["sensitivity"]
    base_key = sw["baseline"]["key"]
    fin = sw["best_final"]
    rows = sw["best_final_rows"]
    passed = sum(1 for r in rows if r[4])
    L = ["# Balance recommendations (from the sim)", "",
         "Generated by `recommend.py` from `results/sweep.json`. **Nothing in Unity was changed.**",
         f"Apply these, playtest, then put the new values in `config/balance.json` and re-run the sim.", "",
         f"Recommended setup passes **{passed}/{len(rows)}** targets (current values: "
         f"{sum(1 for r in sw['baseline']['rows'] if r[4])}/{len(sw['baseline']['rows'])}). "
         "Full numbers and charts: `report.html`.", ""]
    if not sw.get("all_pass"):
        L += ["> No setup in the sweep hit every target. This is the closest one found; the targets it still misses are listed at the end.", ""]
    L += ["## Changes, file by file", ""]
    by_file = {}
    for knob, val in best["setting"].items():
        cur = current_value(cfg, knob, sw)
        if cur == val:
            continue
        by_file.setdefault(UNITY[knob][0], []).append((knob, cur, val))
    for fpath, items in by_file.items():
        L.append(f"### `{fpath}`")
        L.append("")
        if fpath.endswith(".csv") and "upgrade_cost_mult" in best["setting"]:
            L.append("**Use the price table below for the final CostLiters values.** It already combines the ×"
                     f"{best['setting']['upgrade_cost_mult']} on every item with the item changes in this table "
                     "(e.g. W4 20 → 10 → ×1.25 = 13).")
            L.append("")
        L.append("| Field | Before | After | Why |")
        L.append("|---|---|---|---|")
        for knob, cur, val in items:
            s = sens.get(knob, {})
            eff = s.get("effect", {})
            lo, hi = s.get("low", {}), s.get("high", {})
            rank = (f"Sensitivity rank {sw['sensitivity_rank'].index(knob)+1}/{len(sw['sensitivity_rank'])}. "
                    if knob in sw["sensitivity_rank"] else "Not in the sensitivity pass. ")
            why = (rank +
                   (f"Low {lo.get('value')}: Normal median day {fmt(lo.get('key',{}).get('normal_median_day'))}, escape {pct(lo.get('key',{}).get('normal_escape'))}; "
                   f"high {hi.get('value')}: {fmt(hi.get('key',{}).get('normal_median_day'))}, escape {pct(hi.get('key',{}).get('normal_escape'))}." if lo else ""))
            note = UNITY[knob][2]
            if UNITY[knob][1].endswith("factor)") or knob in ("room_water_mult", "upgrade_cost_mult"):
                shown_before, shown_after = ("×1.0", f"×{val}") if knob == "room_water_mult" else (cur, val)
            else:
                shown_before, shown_after = cur, val
            L.append(f"| {UNITY[knob][1]} | {shown_before} | {shown_after} | {why} {note} |")
        L.append("")
    if any(k == "room_water_mult" for k in best["setting"]):
        f = best["setting"]["room_water_mult"]
        rc = cfg["rooms"]
        L += [f"Room water ×{f} means: Cache Base {rc['cache_base']} → {round(rc['cache_base']*f,2)}, "
              f"Cache Per D {rc['cache_per_d']} → {round(rc['cache_per_d']*f,2)}, Cistern Base {rc['cistern_base']} → "
              f"{round(rc['cistern_base']*f,2)}, Cistern Per D {rc['cistern_per_d']} → {round(rc['cistern_per_d']*f,2)}.", ""]
    if best["setting"].get("upgrade_cost_mult", 1.0) != 1.0:
        f = best["setting"]["upgrade_cost_mult"]
        import math
        L += ["New Build and Skills prices (CostLiters × factor, rounded up):", "",
              "| Id | Name | Before | After |", "|---|---|---|---|"]
        after_cfg = config.balance(best["overrides"])
        for uid, u in cfg["upgrades"].items():
            L.append(f"| {uid} | {u['name']} | {u['cost']} | {math.ceil(after_cfg['upgrades'][uid]['cost']*f-1e-4)} |")
        L.append("")
    L += ["## What changes for players", "", "| Metric | Before | After |", "|---|---|---|"]
    nb, na = base_key, fin["normal"]
    L += [f"| Normal: escaped | {pct(nb['normal_escape'])} | {pct(na['escape_rate'])} |",
          f"| Normal: game over | {pct(nb['normal_game_over'])} | {pct(na['game_over_rate'])} |",
          f"| Normal: median escape day (escapers) | {fmt(nb['normal_median_day_escapers'])} | {fmt(na['median_escape_day'])} |",
          f"| Normal: real minutes to escape (median) | {fmt(nb['normal_real_min'])} | {fmt(na['real_min_median'])} |",
          f"| Normal: collapses / run | {fmt(nb['normal_collapses'])} | {fmt(na['collapses_mean'])} |",
          f"| Beginner: escaped | {pct(nb['beginner_escape'])} | {pct(fin['beginner']['escape_rate'])} |",
          f"| Beginner: game over | {pct(nb['beginner_game_over'])} | {pct(fin['beginner']['game_over_rate'])} |",
          f"| Skilled: median escape day | {fmt(nb['skilled_median_day'])} | {fmt(fin['skilled']['median_escape_day_all'])} |",
          f"| Skilled: fastest escape day | {fmt(nb['skilled_min_day'])} | {fmt(fin['skilled']['min_escape_day'])} |", ""]
    miss = [r for r in rows if not r[4]]
    if miss:
        L += ["## Targets still missed with this setup", ""]
        for r in miss:
            L.append(f"- **{r[0]}**: {r[1]}: target {r[2]}, got {fmt(r[3])}")
        L.append("")
    L += ["## Not modelled", ""] + [f"- **{k}**: {v}" for k, v in sw["not_modelled"].items()] + [""]
    with open(os.path.join(ROOT, "RECOMMENDATIONS.md"), "w", encoding="utf8") as f:
        f.write("\n".join(L))
    print("wrote RECOMMENDATIONS.md")


def fmt(v):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.2f}" if abs(v) < 10 else f"{v:.1f}"
    return str(v)


def pct(v):
    return "-" if v is None else f"{v:.0%}"


if __name__ == "__main__":
    main()
